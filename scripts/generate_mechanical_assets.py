"""Generate original mesh-room geometry and simple-to-complex joint demos."""
from pathlib import Path
import copy,json,math
root=Path(__file__).resolve().parents[1]
# Own, deterministic triangle environment, in world units.
vertices=[];faces=[]
def quad(a,b,c,d):
    i=len(vertices)+1;vertices.extend([a,b,c,d]);faces.extend([(i,i+1,i+2),(i,i+2,i+3)])
quad((-9,0,9),(9,0,9),(9,0,-14),(-9,0,-14))
quad((-9,0,9),(-9,3,9),(9,3,9),(9,0,9))
for x in (-9,9):quad((x,0,9),(x,0,-14),(x,3,-14),(x,3,9))
quad((-9,0,-14),(9,0,-14),(9,3,-14),(-9,3,-14))
quad((-5,0,-1),(-2,0,-1),(-2,2,-6),(-5,2,-6))
for i in range(5):
    z=-1-i;h=(i+1)*.3
    quad((1,h,z),(4,h,z),(4,h,z-1),(1,h,z-1))
    quad((1,h-.3,z),(4,h-.3,z),(4,h,z),(1,h,z))
    quad((1,0,z),(1,h,z),(1,h,z-1),(1,0,z-1))
    quad((4,0,z),(4,0,z-1),(4,h,z-1),(4,h,z))
quad((5,0,-11),(5,3,-11),(5,3,-7),(5,0,-7))
text='# SPDX-License-Identifier: MPL-2.0\n# Original Afterlight mesh-room fixture; generated by scripts/generate_mechanical_assets.py\n'
text+=''.join('v %g %g %g\n'%v for v in vertices)+''.join('f %d %d %d\n'%f for f in faces)
(root/'sandbox/assets/mesh-room.obj').write_text(text)
base=json.loads((root/'sandbox/scenes/physics-drop.afterlight.json').read_text())
def create(name,hard):
    s=copy.deepcopy(base);s['version']=14;s['joints']=[];s['next_joint']='1'
    s['objects']=[o for o in s['objects'] if int(o['id'])>=4]
    s['assets'].append(dict(name='room_mesh',kind='mesh',path='../assets/mesh-room.obj'))
    template=copy.deepcopy(next(o for o in s['objects'] if o['name']=='Push crate'))
    def shape(label,pos,half,dynamic=True,sphere=False,spin=None,velocity=None,gravity=1,mass=1):
        o=copy.deepcopy(template);o.update(id=s['next_id'],parent='0',name=label,mesh='physics_sphere' if sphere else 'cube',position=pos,rotation=[0,0,0],scale=[half[0]/.65]*3 if sphere else [h/.65 for h in half]);s['next_id']=str(int(s['next_id'])+1)
        o['collider'].update(type='sphere' if sphere else 'box',trigger=False,center=[0,0,0]);o['body'].update(enabled=dynamic,type='dynamic' if dynamic else 'static',mass=mass,gravity_scale=gravity,velocity=velocity or [0,0,0],angular_velocity=spin or [0,0,0],continuous=True,linear_damping=.08,angular_damping=.15)
        o['material']['base_color']=[.25,.65,.8,1] if sphere else [.9,.55,.2,1];s['objects'].append(o);return o
    def joint(a,b='0',anchor_a=None,anchor_b=None,distance=1,hinge=False,axis=None,low=-math.pi,high=math.pi):
        j=dict(id=s['next_joint'],name=('Hinge' if hinge else 'Distance')+' '+a,type='hinge' if hinge else 'distance',enabled=True,collide_connected=False,a=a,b=b,anchor_a=anchor_a or [0,0,0],anchor_b=anchor_b or [0,0,0],distance=distance,axis_a=axis or [0,1,0],axis_b=axis or [0,1,0],reference_a=[1,0,0],reference_b=[1,0,0],limits_enabled=hinge,lower_limit=low,upper_limit=high);s['next_joint']=str(int(s['next_joint'])+1);s['joints'].append(j)
    room=shape('Imported collision room',[0,0,0],[.65]*3,False);room['mesh']='room_mesh';room['collider'].update(type='mesh',center=[0,0,0]);room['material']['base_color']=[.42,.5,.58,1]
    pendulum=shape('Distance pendulum',[-6,3,-3],[.3]*3,True,True,velocity=[1.5,0,0],mass=2);joint(pendulum['id'],anchor_b=[-6,5,-3],distance=2)
    if hard:
        previous='0'
        for i in range(6):
            ball=shape('Chain '+str(i),[-6,5-i*.7,-10],[.22]*3,True,True,mass=1+i*.25,velocity=[.8,0,0] if i==5 else None)
            joint(ball['id'],previous,anchor_b=[-6,5.7,-10] if not int(previous) else [0,0,0],distance=.7);previous=ball['id']
        door=shape('Hinged door',[-3,1.5,-8],[1,1.5,.12],spin=[0,1.5,0]);joint(door['id'],anchor_a=[-1,0,0],anchor_b=[-4,1.5,-8],hinge=True,low=-1.2,high=1.2)
        beam=shape('Swinging beam',[6,2.6,-3],[.15,1.5,.3],spin=[0,0,1.2]);joint(beam['id'],anchor_a=[0,1.5,0],anchor_b=[6,4.1,-3],hinge=True,axis=[0,0,1],low=-.8,high=.8)
        seesaw=shape('Seesaw',[0,.7,-11],[2,.12,.8],mass=8,spin=[0,0,.4]);joint(seesaw['id'],anchor_b=[0,.7,-11],hinge=True,axis=[0,0,1],low=-.3,high=.3)
        for i in range(3):shape('Ramp ball '+str(i),[-3.5,3+i*.7,-4],[.24]*3,True,True)
        shape('Fast mesh projectile',[7,1,-9],[.12]*3,True,True,velocity=[-120,0,0],gravity=0)
        shape('Spinning box',[2,3,-9],[.6,.12,.25],spin=[0,0,30])
        marker=shape('Room switch marker',[0,.9,-12],[.5,1,.5],False);marker['visible']=False;marker['collider']['trigger']=True;marker['gameplay'].update(role='checkpoint',checkpoint_order=1)
    (root/'sandbox/scenes'/(name+'.afterlight.json')).write_text(json.dumps(s,indent=2)+'\n')
create('mesh-room',False);create('mechanical-playground',True)
